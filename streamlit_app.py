@st.cache_data
def geocode_address(address):
    ors_client = get_ors_client()
    geocode_result = ors_client.pelias_search(text=address)
    if geocode_result and geocode_result["features"]:
        coordinates = geocode_result["features"][0]["geometry"]["coordinates"]
        return coordinates[0], coordinates[1]
    else:
        st.error(f"Address '{address}' could not be geocoded.")
        return None


