def get_ors_client():
    return client.Client(key=ORS_API_KEY)


@st.cache_data
def get_isochrones(
    lonlats: list[tuple[float, float]],
    profile: str,
    max_travel_time_s: int,
    interval: int,
) -> dict:
    """
    Generate isochrones for given locations and travel profile.

    Parameters:
    lonlats (list of tuples): List of (longitude, latitude) pairs representing locations.
    profile (str): Travel profile (e.g., 'driving-car', 'cycling', etc.).
    max_travel_time_s (int): Maximum travel time in seconds (must be > 0 and <= 3600).
    interval (int): Interval in seconds for isochrone generation (must be > 0).

    Returns:
    dict: Isochrones data generated by the ORS client.

    Raises:
    AssertionError: If profile is not in ORS_PROFILES, or if interval or max_travel_time_s are out of valid range.
    """
    assert profile in ORS_PROFILES
    assert interval > 0
    assert (
        max_travel_time_s > 0
        and max_travel_time_s <= timedelta(minutes=30).total_seconds()
    )
    return isochrones.isochrones(
        client=get_ors_client(),
        locations=lonlats,
        profile=profile,
        range=[max_travel_time_s],
        interval=interval,
        range_type="time",
    )


